# ==================== 文本提取器 ====================

class TextExtractor(HTMLParser):
    """从HTML中提取纯文本，过滤导航/脚本等"""

    def __init__(self):
        super().__init__()
        self.parts = []
        self.skip = False
        self.skip_tags = {'script', 'style', 'nav', 'header', 'footer', 'aside', 'select', 'input'}

    def handle_starttag(self, tag, attrs):
        if tag in self.skip_tags:
            self.skip = True

    def handle_endtag(self, tag):
        if tag in self.skip_tags:
            self.skip = False

    def handle_data(self, data):
        if not self.skip:
            s = data.strip()
            if s and len(s) > 1:
                self.parts.append(s)


def extract_text(html_content):
    """从HTML提取纯文本"""
    ext = TextExtractor()
    ext.feed(html_content)
    return '\n'.join(ext.parts)


def clean_law_text(text, title):
    """清理法律文本，去除无关内容"""
    # 去除页眉页脚
    text = re.sub(r'(?:首页|法律法规|华律网|在线咨询|免费发布|坐等律师|需求发布).*?\n', '', text)
    text = re.sub(r'(?:找律师|免费法律咨询|罪名库|法律常识|委托律师|在线律师).*?\n', '', text)
    # 去除导航
    text = re.sub(r'(?:民商法类|行政法类|经济法类|社会法类|刑法类|国际法类).*?\n', '', text)
    text = re.sub(r'(?:婚姻家庭|债权债务|合同纠纷|交通事故|医疗纠纷|拆迁安置).*?\n', '', text)
    # 去除律师广告
    text = re.sub(r'(?:高级合伙人律师|主任律师|执业律师|咨询电话|联系方式).*?\n', '', text)
    # 去除多余空行
    text = re.sub(r'\n{3,}', '\n\n', text)
    return text.strip()


# ==================== 进度管理 ====================

def load_progress():
    if PROGRESS_FILE.exists():
        with open(PROGRESS_FILE, 'r', encoding='utf-8') as f:
            return json.load(f)
    return {"downloaded": [], "failed": []}


def save_progress(progress):
    with open(PROGRESS_FILE, 'w', encoding='utf-8') as f:
        json.dump(progress, f, ensure_ascii=False, indent=2)


