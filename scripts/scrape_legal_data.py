def fetch_law_from_66law(keyword):
    """从66law.cn获取法律全文"""
    # 查找URL
    url = None
    for key, u in LAW_URL_MAP_66LAW.items():
        if key in keyword or keyword in key:
            url = u
            break

    if not url:
        return None, None

    try:
        r = requests.get(url, headers=HEADERS, timeout=20)
        r.encoding = 'utf-8'
        if r.status_code != 200:
            return None, None

        text = extract_text(r.text)
        text = clean_law_text(text, keyword)

        # 验证是否包含法条
        articles = re.findall(r'第[一二三四五六七八九十百千零]+条', text)
        if len(articles) < 5:
            return None, None

        # 提取标题
        title_match = re.search(r'中华人民共和国.{2,20}法', text)
        title = title_match.group() if title_match else keyword

        return text, title

    except Exception as e:
        print(f"    66law.cn获取失败: {e}")
        return None, None


def fetch_law_from_flk(keyword):
    """从flk.npc.gov.cn获取法律结构（作为备选）"""
    import urllib3
    urllib3.disable_warnings()

    api_headers = {
        'User-Agent': HEADERS['User-Agent'],
        'Accept': 'application/json, text/plain, */*',
        'Content-Type': 'application/json;charset=UTF-8',
        'Origin': 'https://flk.npc.gov.cn',
        'Referer': 'https://flk.npc.gov.cn/',
    }

    body = {
        'searchRange': 1, 'sxrq': [], 'gbrq': [], 'searchType': 2,
        'sxx': [], 'gbrqYear': [], 'flfgCodeId': [], 'zdjgCodeId': [],
        'searchContent': keyword, 'xgzlSearch': False,
        'page': 1, 'size': 3, 'time': int(time.time() * 1000),
    }

    try:
        r = requests.post('https://flk.npc.gov.cn/law-search/search/list',
                         headers=api_headers, json=body, timeout=15, verify=False)
        data = r.json()
        rows = data.get('rows', [])
        if not rows:
            return None, None

        # 找到匹配的结果
        for row in rows:
            title = re.sub(r'<[^>]+>', '', row.get('title', ''))
            if keyword in title or title in keyword:
                bbbs = row.get('bbbs', '')
                # 获取详情
                params = {'bbbs': bbbs, 'time': int(time.time() * 1000)}
                r2 = requests.get('https://flk.npc.gov.cn/law-search/search/flfgDetails',
                                 headers=api_headers, params=params, timeout=15, verify=False)
                detail = r2.json().get('data', {})

                # 从content树构建文本
                content = detail.get('content', {})
                if content:
                    text = build_text_from_tree(content)
                    if len(text) > 1000:
                        return text, title

    except Exception as e:
        print(f"    flk.npc.gov.cn获取失败: {e}")

    return None, None


def build_text_from_tree(node, depth=0):
    """从flk API的content树构建法律文本"""
    parts = []
    title = node.get('title', '')
    children = node.get('children', [])

    if title:
        if depth == 0:
            parts.append(title)
        elif depth == 1:
            parts.append(f"\n{title}\n")
        elif depth == 2:
            parts.append(f"\n{title}\n")
        else:
            parts.append(title)

    for child in children:
        parts.append(build_text_from_tree(child, depth + 1))

    return '\n'.join(parts)


def save_text_to_docx(text, title, output_path):
    """将文本保存为.docx文件"""
    from docx import Document

    doc = Document()
    doc.add_heading(title, level=0)

    for line in text.split('\n'):
        line = line.strip()
        if not line:
            continue
        # 检测结构标题
        if re.match(r'^第[一二三四五六七八九十百千零]+[编章节]', line):
            doc.add_heading(line, level=1)
        elif re.match(r'^第[一二三四五六七八九十百千零]+条', line):
            doc.add_paragraph(line, style='List Number')
        elif line.startswith('【') and line.endswith('】'):
            doc.add_heading(line, level=2)
        else:
            doc.add_paragraph(line)

    os.makedirs(os.path.dirname(output_path) or '.', exist_ok=True)
    doc.save(output_path)
    return output_path


