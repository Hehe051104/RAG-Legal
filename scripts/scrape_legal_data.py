        if not text:
            # 尝试从flk.npc.gov.cn获取
            print(f"  [备选] 从flk.npc.gov.cn...")
            text, title = fetch_law_from_flk(keyword)

        if text and len(text) > 1000:
            articles = re.findall(r'第[一二三四五六七八九十百千零]+条', text)
