    for i, (name, keyword, doc_type) in enumerate(PRIORITY_LAWS):
        print(f"\n[{i+1}/{len(PRIORITY_LAWS)}] {name}")

        if name in progress['downloaded']:
            print(f"  [跳过] 已完成")
            success += 1
            continue

