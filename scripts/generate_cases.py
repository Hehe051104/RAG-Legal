def main():
    os.makedirs(CASES_DIR, exist_ok=True)

    filter_type = sys.argv[1] if len(sys.argv) > 1 else None

    total = 0
    saved = 0

    for group_key, (group_name, cases) in ALL_CASE_GROUPS.items():
        if filter_type and group_key != filter_type:
            continue

        print(f"\n{'='*40}")
        print(f"  {group_name} ({len(cases)} 个案例)")
        print(f"{'='*40}")

        for case in cases:
            total += 1
            if save_case(case):
                print(f"  [新增] {case['title']}")
                saved += 1
            else:
                print(f"  [跳过] {case['title']}")

    print(f"\n{'='*60}")
    print(f"完成! 共 {total} 个案例，新增 {saved} 个，跳过 {total - saved} 个")
    print(f"案例保存目录: {CASES_DIR}")


